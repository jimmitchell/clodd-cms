#!/usr/bin/env php
<?php

/**
 * Generate the nginx 301s for every address a post has moved away from.
 *
 * A permalink here is derived, never stored, so a rename is internally
 * consistent — feeds, sitemap, search index and neighbour links all follow at
 * once. The outside world does not: someone's bookmark, another blog's link and
 * a search engine's index all still name the old URL, and Builder deletes the
 * directory that used to answer it. post_legacy_urls remembers those addresses;
 * this turns them into rules.
 *
 * Exact-match locations rather than a map: they need no http-level context (so
 * the snippet drops straight into the server block), and nginx resolves an
 * exact location before any regex, so these win over the dated-post block with
 * no ordering to get right. Both the slashed and slashless forms are emitted,
 * because that block rewrites either.
 *
 * Writes to stdout. Redirect it, move it into place, reload nginx:
 *
 *   php bin/build-redirects.php > /tmp/cms-legacy-redirects.conf
 *   sudo mv /tmp/cms-legacy-redirects.conf /etc/nginx/snippets/cms-legacy-redirects.conf
 *   sudo nginx -t && sudo systemctl reload nginx
 */

define('CMS_ROOT', dirname(__DIR__));
define('CMS_VERSION', trim(file_get_contents(CMS_ROOT . '/VERSION')));

require CMS_ROOT . '/vendor/autoload.php';

use CMS\Database;
use CMS\Post;

if (!class_exists(Database::class)) {
    fwrite(STDERR, "Error: autoloader not found. Run 'composer install' first.\n");
    exit(1);
}

$config   = require CMS_ROOT . '/config.php';
$db       = new Database($config['paths']['data'] . '/cms.db');
$timezone = $db->getSetting('timezone', '');

// Published and not deleted only. A legacy address whose post has since been
// unpublished has nowhere to point: 404 is the honest answer, and a 301 to a
// page that also 404s is a worse one.
$rows = $db->select(
    "SELECT l.path AS old_path, p.published_at, p.slug
       FROM post_legacy_urls l
       JOIN posts p ON p.id = l.post_id
      WHERE p.status = 'published'
        AND p.deleted_at IS NULL
        AND p.published_at IS NOT NULL
      ORDER BY l.path"
);

printf("# Generated by bin/build-redirects.php — do not edit by hand.\n");
printf("# %d redirect%s, %s.\n\n", count($rows), count($rows) === 1 ? '' : 's', date('Y-m-d H:i'));

$written = 0;
foreach ($rows as $row) {
    $old = '/' . trim((string) $row['old_path'], '/');
    $new = '/' . Post::datePath((string) $row['published_at'], (string) $row['slug'], $timezone) . '/';

    // A post moved back onto an address it once held would redirect to itself,
    // which nginx answers as a loop. recordLegacyPath() clears the row when that
    // happens; this is the backstop for a row written before it did.
    if ($old . '/' === $new) {
        fwrite(STDERR, "skipping self-redirect: {$old}\n");
        continue;
    }

    printf("location = %-46s { return 301 %s; }\n", $old, $new);
    printf("location = %-46s { return 301 %s; }\n", $old . '/', $new);
    $written++;
}

fwrite(STDERR, "{$written} redirects written.\n");
